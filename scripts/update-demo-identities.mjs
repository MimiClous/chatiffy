// Refresh public preview metadata. No Twitch account, OAuth token or chat connection is used.
// Run manually with Node 20+: node scripts/update-demo-identities.mjs
import { readFile, writeFile } from 'node:fs/promises';
const rosterSource = await readFile(new URL('../src/client/demo-roster.ts', import.meta.url), 'utf8');
const roster = [...rosterSource.matchAll(/\['([^']+)', '([^']+)'\]/g)].map(([, original, parody]) => ({ original, parody }));
async function request(url, options) {
  const response = await fetch(url, { ...options, signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw new Error(`${new URL(url).host}: HTTP ${response.status}`);
  return response;
}
async function gql(query) {
  const data = await (await request('https://gql.twitch.tv/gql', { method: 'POST', headers: {
    'Client-ID': 'kimne78kx3ncx6brgo4mv6wki5h1ko', 'Content-Type': 'application/json'
  }, body: JSON.stringify({ query }) })).json();
  if (data.errors?.length) throw new Error(JSON.stringify(data.errors));
  return data.data;
}
const index = await (await request('https://mineshield.gg/members')).text();
const cards = [...index.matchAll(/<a href="\/members\/([^"/]+)"[^>]*>[\s\S]*?alt="([^"]+)"/g)];
const identities = [];
// Keep concurrency bounded for the public member directory.
for (let start = 0; start < roster.length; start += 4) {
  identities.push(...await Promise.all(roster.slice(start, start + 4).map(async member => {
    const card = cards.find(([, , name]) => name.toLowerCase() === member.original.toLowerCase());
    if (!card) throw new Error(`Member page not found: ${member.original}`);
    const page = await (await request(`https://mineshield.gg/members/${card[1]}`)).text();
    const login = /https?:\/\/(?:www\.)?twitch\.tv\/([a-z0-9_]+)/i.exec(page)?.[1]?.toLowerCase();
    if (!login) throw new Error(`Public Twitch link not found: ${member.original}`);
    return { ...member, login };
  })));
}
const users = {};
for (let start = 0; start < identities.length; start += 5) {
  const query = 'query { ' + identities.slice(start, start + 5).map((m, i) => `u${start + i}: user(login: ${JSON.stringify(m.login)}) { id login roles { isPartner } displayBadges { setID version title imageURL(size: DOUBLE) } }`).join('\n') + ' }';
  Object.assign(users, await gql(query));
}
const catalog = (await gql('query { badges { setID version title imageURL(size: DOUBLE) } }')).badges;
const partner = catalog.find(b => b.setID === 'partner' && b.version === '1');
if (!partner) throw new Error('Verified partner badge missing from Twitch catalog');
const output = {};
for (const [i, member] of identities.entries()) {
  const user = users[`u${i}`];
  if (!user || user.login !== member.login) throw new Error(`Twitch identity mismatch: ${member.original}`);
  const badges = [...user.displayBadges];
  if (user.roles?.isPartner && !badges.some(b => b.setID === 'partner')) badges.push(partner);
  output[member.parody] = { login: user.login, userId: user.id,
    badges: badges.filter(b => /^https:\/\/static-cdn\.jtvnw\.net\//.test(b.imageURL)).map(b => ({ url: b.imageURL, title: b.title })) };
}
const source = `// Generated by scripts/update-demo-identities.mjs on ${new Date().toISOString().slice(0, 10)}.\n// Public original Twitch identities; fictional display names remain in demo-roster.ts.\nimport type { DemoNickname } from './demo-roster.js';\nimport type { Badge } from '../shared/contracts.js';\nexport const demoIdentities: Record<DemoNickname, { login: string; userId: string; badges: Badge[] }> = ${JSON.stringify(output, null, 2)};\n`;
// Write only after every original identity and the badge catalog were validated.
await writeFile(new URL('../src/client/demo-identities.ts', import.meta.url), source);
console.log(`Updated ${identities.length} original identities and their public Twitch badges.`);
